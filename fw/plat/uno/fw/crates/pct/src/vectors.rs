//! Fixed ECDH test key pairs for the key-agreement PCT.
//!
//! Each pair is `COUNT = 0` (`dIUT`, `QIUTx`, `QIUTy`) from the NIST CAVP ECC
//! CDH primitive test vectors (SP 800-56A).
//! Values are big-endian, as NIST publishes them. The PCT reverses them into
//! the Uno PAL's little-endian vault and wire formats.

use azihsm_fw_hsm_pal_traits::HsmEccCurve;

/// A fixed ECDH test key pair, big-endian.
pub(crate) struct EcdhTestPair {
    /// Private scalar `d`.
    pub(crate) d: &'static [u8],
    /// Public point X coordinate.
    pub(crate) qx: &'static [u8],
    /// Public point Y coordinate.
    pub(crate) qy: &'static [u8],
}

/// Returns the fixed ECDH test key pair for `curve`.
pub(crate) fn ecdh_test_pair(curve: HsmEccCurve) -> EcdhTestPair {
    match curve {
        HsmEccCurve::P256 => EcdhTestPair {
            d: &P256_D,
            qx: &P256_QX,
            qy: &P256_QY,
        },
        HsmEccCurve::P384 => EcdhTestPair {
            d: &P384_D,
            qx: &P384_QX,
            qy: &P384_QY,
        },
        HsmEccCurve::P521 => EcdhTestPair {
            d: &P521_D,
            qx: &P521_QX,
            qy: &P521_QY,
        },
    }
}

/// Copies big-endian `src` into the front of `dst` in little-endian order.
///
/// `dst` must be at least `src.len()` bytes; bytes past `src.len()` are left
/// unchanged, so a zeroed `dst` keeps its zero padding.
pub(crate) fn be_to_le(src: &[u8], dst: &mut [u8]) {
    for (d, s) in dst.iter_mut().zip(src.iter().rev()) {
        *d = *s;
    }
}


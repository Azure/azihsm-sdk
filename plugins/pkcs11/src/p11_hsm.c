{
    p11_slot_t *slot = &g_p11.slots[0];
    slot->present = true;
    slot->token_initialized = true;
    snprintf(slot->device_path, sizeof(slot->device_path), "azihsm-placeholder-0");
    snprintf(slot->label, sizeof(slot->label), "AZIHSM (no device)");
    snprintf(slot->serial, sizeof(slot->serial), "AZIHSM000000");
    slot->api_rev_major = 1;
    slot->api_rev_minor = 0;
    return 1;
}

